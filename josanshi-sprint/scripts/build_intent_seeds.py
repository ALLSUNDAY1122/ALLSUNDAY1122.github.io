COGNITIVE_MODES = [
    "concept-discrimination",
    "assessment",
    "risk-recognition",
    "care-decision",
    "integration",
]


def fail(message: str) -> None:
    raise SystemExit(f"FAIL: {message}")


def build_payload() -> dict:
    blueprint = json.loads(BLUEPRINT.read_text(encoding="utf-8"))
    blueprint_topics = {topic["topicId"] for topic in blueprint["topics"]}
    if set(INTENTS) != blueprint_topics:
        fail(
            f"intent topics do not match blueprint; missing={sorted(blueprint_topics-set(INTENTS))}, "
            f"extra={sorted(set(INTENTS)-blueprint_topics)}"
        )

    topics = []
    for topic in blueprint["topics"]:
        topic_id = topic["topicId"]
        seeds = INTENTS[topic_id]
        if len(seeds) != topic["bankTarget"] or len(seeds) != 5:
            fail(f"{topic_id}: expected exactly 5 semantic intents")
        intents = []
        for index, (focus, keywords) in enumerate(seeds, start=1):
            intents.append({
                "intentId": f"{topic_id}-I{index}",
                "focus": focus,
                "cognitiveMode": COGNITIVE_MODES[index - 1],
                "officialKeywords": keywords,
                "status": "planned",
            })
        topics.append({
            "topicId": topic_id,
            "subject": topic["subject"],
            "topicTitle": topic["title"],
            "intents": intents,
        })
    return {
        "schemaVersion": "1.0",
        "qualification": blueprint["qualification"],
        "scopeSource": "保健師助産師看護師国家試験出題基準 令和5年版",
        "policy": "Planning intents only. Each production question must be independently sourced and may not copy protected source expression.",
        "topics": topics,
    }


def validate(payload: dict) -> None:
    topics = payload["topics"]
    if len(topics) != 66:
        fail(f"expected 66 topics, found {len(topics)}")
    all_intents = [intent for topic in topics for intent in topic["intents"]]
    if len(all_intents) != 330:
        fail(f"expected 330 intents, found {len(all_intents)}")
    ids = [intent["intentId"] for intent in all_intents]
    if len(ids) != len(set(ids)):
        fail("intent IDs must be unique")
    for topic in topics:
        intents = topic["intents"]
        focuses = [intent["focus"].strip() for intent in intents]
        if len(focuses) != len(set(focuses)):
            fail(f"{topic['topicId']}: duplicate focus")
        modes = [intent["cognitiveMode"] for intent in intents]
        if len(set(modes)) != 5:
            fail(f"{topic['topicId']}: cognitive modes must be diverse")
        if any(not intent["officialKeywords"] for intent in intents):
            fail(f"{topic['topicId']}: official keyword group missing")

    # Prevent the easiest form of padding: identical focus reused anywhere in bank.
    global_focuses = [intent["focus"].strip().lower() for intent in all_intents]
    duplicates = sorted({focus for focus in global_focuses if global_focuses.count(focus) > 1})
    if duplicates:
        fail(f"globally duplicate semantic focuses: {duplicates[:10]}")

    print("PASS: #14 semantic intent seeds")
    print("  66 topics x 5 distinct intents = 330")
    print("  5 cognitive modes per topic")
    print("  exact duplicate focus = 0")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    payload = build_payload()
    validate(payload)
    if not args.check:
        args.output.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"WROTE: {args.output}")


if __name__ == "__main__":
    main()
